"""Translate Coraza JSON audit events into ``LogIngestRequest`` payloads.

The mapping contract is documented in ``configs/coraza/README.md`` and mirrors the
``LogIngestRequest`` schema in ``src/backend/app/schemas/log.py``. This module is a
pure, defensive translator: it never raises on malformed input and returns ``None``
for events that cannot be turned into a valid ingest payload (so the shipper can
skip them instead of wedging).

## Actual coraza-spoa v0.6.1 JSON format quirks

The README mapping table was written against the expected coraza audit schema, but
the actual coraza-spoa v0.6.1 binary does not populate ``messages[].data``; that
field is always ``null``. Rule id, rule message, and rule severity are instead
embedded in the ``messages[].error_message`` log-formatted string, e.g.:

    [id "941100"] [msg "XSS Attack Detected"] [severity "critical"]

Similarly the timestamp uses ``"YYYY/MM/DD HH:MM:SS"`` (no timezone, implicitly
UTC) and ``transaction.variables`` is absent. The mapping handles both the
documented schema and the actual one so it does not break if a future version of
coraza-spoa populates ``data``.
"""

from __future__ import annotations

import re
from datetime import UTC, datetime
from ipaddress import ip_address
from typing import Any

# Regex to extract bracketed fields from coraza-spoa error_message strings.
# e.g.  [id "941100"] [msg "XSS Attack Detected"] [severity "critical"]
_BRACKET_INT = re.compile(r'\[id "(\d+)"\]')
_BRACKET_MSG = re.compile(r'\[msg "([^"]+)"\]')
_BRACKET_SEV = re.compile(r'\[severity "([\w]+)"\]')

# Text the SPOA writes after the `[client "..."]` field and before the rule's
# own bracket fields, e.g. "Coraza: Access denied (phase 2). Inbound Anomaly
# Score Exceeded (Total Score: 5)". Also generated by Coraza, never by the
# request, unlike the [data "..."] / [uri "..."] fields that echo it.
_NARRATION = re.compile(r'\[client "[^"]*"\]\s*([^\[]*)')

# The CRS blocking-evaluation rule embeds the total inbound anomaly score in its
# message text, e.g. "Inbound Anomaly Score Exceeded (Total Score: 20)". Since
# coraza-spoa v0.6.1 does not expose transaction.variables, this is the only
# reliable source of the score for blocked requests.
_TOTAL_SCORE = re.compile(r"\(Total Score:\s*(\d+)\)")

# Per-rule severity strings that indicate a blocking/deny action when the
# interruption flag is missing from the event.
_DENY_SEVERITY_STRINGS = frozenset({"emergency", "alert", "critical"})

# CRS blocking-evaluation rules (REQUEST-949 / RESPONSE-959). They only match
# once the anomaly score reaches the policy threshold, so seeing one on a
# transaction that was not interrupted means a DetectionOnly policy let
# through a request it would otherwise have blocked.
_ANOMALY_EVALUATION_RULE_IDS = frozenset({949110, 949111, 959100, 959101})

# LogIngestRequest.vhost max_length. Kept here so the shipper does not import
# the backend schema.
_VHOST_MAX_LENGTH = 255

# LogIngestRequest.method max_length. A client picks the method token, so an
# over-long one must not make the event unmappable: the backend answers 422 for
# it, and a 422 is a poison pill the shipper can only dead-letter.
_METHOD_MAX_LENGTH = 16

# Timestamp formats Coraza may emit in addition to ISO 8601.
_CORAZA_TS_FORMATS = (
    "%Y/%m/%d %H:%M:%S",        # actual coraza-spoa v0.6.1: "2026/05/31 13:29:17"
    "%d/%b/%Y:%H:%M:%S.%f %z",  # Apache-style with microseconds and tz
    "%d/%b/%Y:%H:%M:%S %z",     # Apache-style without microseconds
)


# ---------------------------------------------------------------------------
# Public entry point
# ---------------------------------------------------------------------------

def coraza_event_to_ingest(event: dict[str, Any]) -> dict[str, Any] | None:
    """Map one Coraza audit event to an ingest payload, or ``None`` to skip it."""

    transaction = _as_dict(event.get("transaction"))
    if not transaction:
        return None

    request = _as_dict(transaction.get("request"))
    method = _clean_str(request.get("method"))
    request_uri = _clean_str(request.get("uri"))
    source_ip = _valid_ip(transaction.get("client_ip"))

    # These three are required by the backend; without them the event can never be
    # accepted, so skipping avoids a poison-pill that would block the pipeline.
    if not method or not request_uri or source_ip is None:
        return None

    messages = event.get("messages")
    messages = messages if isinstance(messages, list) else []
    is_interrupted = transaction.get("is_interrupted")

    # Prefer the structured data field; fall back to parsing error_message.
    primary_data = _primary_rule_data(messages)

    action = _action(is_interrupted, primary_data, messages)
    anomaly_score = _anomaly_score(transaction.get("variables"))
    if anomaly_score is None:
        anomaly_score = _anomaly_score_from_messages(messages)

    payload: dict[str, Any] = {
        "producer_event_id": _clean_str(transaction.get("id")),
        "event_at": _event_at(transaction.get("timestamp")),
        "vhost": _vhost(request.get("headers")),
        "action": action,
        "source_ip": source_ip,
        "method": method.upper()[:_METHOD_MAX_LENGTH],
        "request_uri": request_uri,
        "status_code": _status_code(transaction.get("response")),
        "rule_id": _rule_id(primary_data),
        "rule_message": _rule_message(primary_data),
        "anomaly_score": anomaly_score,
        "paranoia_level": _paranoia_level(transaction.get("variables")),
        "message": None,
        "raw_context": event,
    }
    return payload


# ---------------------------------------------------------------------------
# Rule data extraction — handles both structured data and error_message string
# ---------------------------------------------------------------------------

class _RuleData:
    """Normalised rule fields extracted from either data dict or error_message."""

    __slots__ = ("id", "msg", "severity_str")

    def __init__(
        self, id: str | None, msg: str | None, severity_str: str | None
    ) -> None:
        self.id = id
        self.msg = msg
        self.severity_str = severity_str


def _primary_rule_data(messages: list[Any]) -> _RuleData | None:
    """Return the first message that carries rule information."""
    for raw in messages:
        msg = _as_dict(raw)

        # Prefer structured data (future coraza-spoa versions may populate this).
        data = _as_dict(msg.get("data"))
        if data:
            return _RuleData(
                id=_clean_str(data.get("id")),
                msg=_clean_str(data.get("msg")),
                severity_str=_clean_str(data.get("severity")),
            )

        # 2. Fall back to parsing error_message (actual coraza-spoa v0.6.1 behaviour).
        error_msg = msg.get("error_message")
        if isinstance(error_msg, str) and error_msg.strip():
            id_match = _BRACKET_INT.search(error_msg)
            msg_match = _BRACKET_MSG.search(error_msg)
            sev_match = _BRACKET_SEV.search(error_msg)
            if id_match or msg_match or sev_match:
                return _RuleData(
                    id=id_match.group(1) if id_match else None,
                    msg=msg_match.group(1) if msg_match else None,
                    severity_str=sev_match.group(1) if sev_match else None,
                )

    return None


# ---------------------------------------------------------------------------
# Field derivation helpers
# ---------------------------------------------------------------------------

def _action(
    is_interrupted: Any, primary_data: _RuleData | None, messages: list[Any]
) -> str:
    if is_interrupted is True:
        return "deny"
    if is_interrupted is False:
        return "monitor" if _anomaly_threshold_exceeded(messages) else "allow"
    # Fallback for older or malformed events where the interruption flag is
    # absent. Do not apply it to explicit False; DetectionOnly policies emit
    # high-severity matches without blocking the request.
    if primary_data is not None and primary_data.severity_str is not None:
        if primary_data.severity_str.lower() in _DENY_SEVERITY_STRINGS:
            return "deny"
    return "allow"


def _message_rule_id(raw: Any) -> int | None:
    """Rule id of one audit message, from structured data or error_message."""
    msg = _as_dict(raw)
    rule_id = _coerce_int(_as_dict(msg.get("data")).get("id"))
    if rule_id is not None:
        return rule_id
    error_msg = msg.get("error_message")
    if isinstance(error_msg, str):
        match = _BRACKET_INT.search(error_msg)
        if match:
            return _coerce_int(match.group(1))
    return None


def _anomaly_threshold_exceeded(messages: list[Any]) -> bool:
    """Whether a CRS blocking-evaluation rule matched on this transaction."""
    return any(
        _message_rule_id(raw) in _ANOMALY_EVALUATION_RULE_IDS for raw in messages
    )


def _rule_id(rd: _RuleData | None) -> int | None:
    if rd is None:
        return None
    rule_id = _coerce_int(rd.id)
    return rule_id if rule_id is not None and rule_id > 0 else None


def _rule_message(rd: _RuleData | None) -> str | None:
    return rd.msg if rd is not None else None


def _event_at(value: Any) -> str:
    if isinstance(value, str):
        text = value.strip()
        # Handle ISO 8601 with or without trailing Z.
        iso = text[:-1] + "+00:00" if text.endswith("Z") else text
        try:
            return datetime.fromisoformat(iso).isoformat()
        except ValueError:
            pass
        for fmt in _CORAZA_TS_FORMATS:
            try:
                dt = datetime.strptime(text, fmt)
                # Formats without timezone info are treated as UTC.
                if dt.tzinfo is None:
                    dt = dt.replace(tzinfo=UTC)
                return dt.isoformat()
            except ValueError:
                continue
    return datetime.now(UTC).isoformat()


def _vhost(headers: Any) -> str:
    headers = _as_dict(headers)
    for key, raw in headers.items():
        if isinstance(key, str) and key.lower() == "host":
            # Header values may be a list (actual coraza-spoa output).
            value = raw[0] if isinstance(raw, list) and raw else raw
            host = _clean_str(value)
            if host:
                # Strip a port ("localhost:8080" → "localhost"), then fit the
                # ingest schema. An empty result cannot be stored.
                host = host.lower().split(":")[0]
                if not host:
                    return "unknown"
                return host[:_VHOST_MAX_LENGTH]
    return "unknown"


def _status_code(response: Any) -> int | None:
    status = _coerce_int(_as_dict(response).get("status"))
    if status is None or not (100 <= status <= 599):
        return None
    return status


def _anomaly_score(variables: Any) -> int | None:
    score = _coerce_int(_tx_variable(variables, "anomaly_score"))
    return score if score is not None and score >= 0 else None


def _anomaly_score_from_messages(messages: list[Any]) -> int | None:
    """Total inbound anomaly score, read only from the CRS blocking message.

    Only the blocking-evaluation rule may supply the score, and only from the
    parts of its message that Coraza generates itself: every other message
    carries request data (a matched value inside `[data "..."]`), and the
    blocking message echoes the request URI, so scanning the whole event let a
    payload containing `(Total Score: N)` forge its own score.
    """
    for raw in messages:
        if _message_rule_id(raw) not in _ANOMALY_EVALUATION_RULE_IDS:
            continue
        msg = _as_dict(raw)
        structured = _as_dict(msg.get("data")).get("msg")
        if isinstance(structured, str):
            score = _score_from_text(structured)
            if score is not None:
                return score
        error_message = msg.get("error_message")
        if isinstance(error_message, str):
            match = _BRACKET_MSG.search(error_message)
            if match is not None:
                score = _score_from_text(match.group(1))
                if score is not None:
                    return score
            # Older CRS builds leave the score out of `[msg ...]` and put it in
            # the summary the SPOA writes after `[client "..."]`.
            narration = _NARRATION.search(error_message)
            if narration is not None:
                score = _score_from_text(narration.group(1))
                if score is not None:
                    return score
    return None


def _score_from_text(text: str) -> int | None:
    match = _TOTAL_SCORE.search(text)
    if match is None:
        return None
    score = _coerce_int(match.group(1))
    return score if score is not None and score >= 0 else None


def _paranoia_level(variables: Any) -> int | None:
    level = _coerce_int(_tx_variable(variables, "paranoia_level"))
    return level if level is not None and 1 <= level <= 4 else None


def _tx_variable(variables: Any, name: str) -> Any:
    tx = _as_dict(_as_dict(variables).get("tx"))
    for key, value in tx.items():
        if isinstance(key, str) and key.lower() == name:
            return value
    return None


# ---------------------------------------------------------------------------
# Low-level helpers
# ---------------------------------------------------------------------------

def _as_dict(value: Any) -> dict[Any, Any]:
    return value if isinstance(value, dict) else {}


def _clean_str(value: Any) -> str | None:
    if isinstance(value, str):
        stripped = value.strip()
        return stripped or None
    if isinstance(value, (int, float)):
        return str(value)
    return None


def _coerce_int(value: Any) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return int(value)
    if isinstance(value, str):
        try:
            return int(value.strip())
        except ValueError:
            return None
    return None


def _valid_ip(value: Any) -> str | None:
    text = _clean_str(value)
    if text is None:
        return None
    try:
        # A scoped address ("fe80::1%eth0") is not a client address and its
        # scope can push the string past the schema's max_length, which would
        # make the whole event unmappable.
        return str(ip_address(text)).split("%")[0]
    except ValueError:
        return None
